-- Outbound affiliate click log for rhythmguitar.org (shared Supabase project).
-- Replaces the previous filesystem-based JSON log, which cannot persist on Vercel.

create table if not exists public.rhythmguitar_outbound_clicks (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz  not null default now(),
  site        text         not null default 'rhythmguitar.org',
  url         text         not null,
  referrer    text,
  user_agent  text
);

create index if not exists rhythmguitar_outbound_clicks_created_at_idx
  on public.rhythmguitar_outbound_clicks (created_at desc);

create index if not exists rhythmguitar_outbound_clicks_url_idx
  on public.rhythmguitar_outbound_clicks (url);

-- RLS on with no policies: the anon/public key gets nothing.
-- Writes and reads happen only through the service-role key in the API route.
alter table public.rhythmguitar_outbound_clicks enable row level security;
